package ru.octomem.util;

/**
 * Единый источник текущего времени для подсистем octomem.
 *
 * <p>Весь код, зависящий от текущего времени (срок жизни, фоновое обслуживание, метки
 * событий), обязан читать время только через этот интерфейс. Прямой вызов
 * {@link System#currentTimeMillis()} или {@link System#nanoTime()} вне
 * {@link SystemClock} запрещён: это проверяется тестом отсутствия системного времени
 * (см. {@code docs/03} §4.4).
 *
 * <p><b>Владение и потоки.</b> Реализации делят состояние с вызывающим кодом; интерфейс
 * сам по себе не навязывает потокобезопасность. {@link SystemClock} безопасен для
 * параллельного использования, потому что не хранит состояния. Управляемые тестовые
 * часы (например, с методами установки и продвижения) не потокобезопасны и принадлежат
 * одному потоку теста; в поставку такие часы не входят.
 *
 * <p>{@link #currentTimeSeconds()} и {@link #nanoTime()} — независимые показания:
 * первое является настенным временем (эпоха Unix, секунды), второе — монотонным
 * счётчиком наносекунд. Одно из них не выводится из другого.
 *
 * @since 1.0
 */
public interface Clock {
    /**
     * Возвращает текущее настенное время в секундах от эпохи Unix.
     *
     * @return секунды эпохи Unix; может быть отрицательным для дат до 1970 года
     */
    long currentTimeSeconds();

    /**
     * Возвращает текущее значение монотонных наносекунд.
     *
     * <p>Начало отсчёта не определено, поэтому разница между двумя показаниями
     * значима, а абсолютное значение — нет. Значение может переполниться только
     * через сотни лет непрерывной работы.
     *
     * @return монотонные наносекунды
     */
    long nanoTime();
}
