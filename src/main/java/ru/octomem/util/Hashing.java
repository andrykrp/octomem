package ru.octomem.util;

import java.util.Objects;

/**
 * Некриптографическое детерминированное хеширование.
 *
 * <p>{@link #hash64(byte[])} реализует стандартный FNV-1a для 64 бит: базис
 * {@code 14695981039346656037} ({@code 0xCBF29CE484222325}) и простое число
 * {@code 1099511628211} ({@code 0x100000001B3}), байты входят в хеш как беззнаковые,
 * умножение выполняется по модулю {@code 2^64}.
 *
 * <p><b>Назначение.</b> Алгоритм детерминирован, не зависит от платформы и годится для
 * внутреннего распределения и быстрых проверок. Он <b>не</b> является криптографическим
 * и не даёт защиты от коллизий: устойчивость к подбору коллизий и к атакам на основе
 * коллизий не заявляется. Такая потребность рассматривается отдельной задачей
 * безопасности, а не этой утилитой.
 *
 * <p>Метод не изменяет входной массив и не удерживает ссылку на него.
 *
 * <p><b>Ошибки.</b> {@code null} даёт {@link NullPointerException}.
 *
 * <p><b>Потоки и владение.</b> Утилита без состояния, безопасна для параллельного
 * использования, не создаётся (закрытый конструктор), ресурсов не удерживает.
 *
 * @since 1.0
 */
public final class Hashing {
    /** Базис FNV-1a 64 бита: {@code 14695981039346656037}. */
    private static final long FNV1A_OFFSET_BASIS = 0xCBF29CE484222325L;
    /** Простое число FNV-1a 64 бита: {@code 1099511628211}. */
    private static final long FNV1A_PRIME = 0x100000001B3L;

    private Hashing() {
        // Утилитный класс: экземпляры не создаются.
    }

    /**
     * Вычисляет 64-битный FNV-1a хеш массива байт.
     *
     * @param data массив байт; на входе не изменяется и не удерживается
     * @return детерминированный 64-битный хеш, представленный битовым шаблоном {@code long}
     * @throws NullPointerException если {@code data} равен {@code null}
     */
    public static long hash64(byte[] data) {
        Objects.requireNonNull(data, "data");
        long hash = FNV1A_OFFSET_BASIS;
        for (byte value : data) {
            hash ^= value & 0xFF;
            hash *= FNV1A_PRIME;
        }
        return hash;
    }
}
